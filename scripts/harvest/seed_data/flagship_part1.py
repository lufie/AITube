def yt(vid: str, ch: str, title: str, total: int, start: int, end: int, rev: int = 18):
    hrs = round(max(0.8, (total * rev * 0.35) / 3600), 1)
    return {
        "kind": "video-cut",
        "platform": "youtube",
        "videoId": vid,
        "channelName": ch,
        "originalTitle": title,
        "totalDurationSec": total,
        "startSec": start,
        "endSec": end,
        "videosReviewedCount": rev,
        "hoursSaved": hrs,
    }


